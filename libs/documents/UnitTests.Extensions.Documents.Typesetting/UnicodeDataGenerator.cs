using System.Globalization;
using System.IO;
using System.Runtime.CompilerServices;
using System.Text;
using System.Text.RegularExpressions;

namespace UnitTests.Extensions.Documents.Typesetting;

/// <summary>
/// Generates <c>Ave.Extensions.Documents.Typesetting/Unicode/UnicodePropertyRanges.g.cs</c> from the Unicode Character
/// Database files committed in <c>assets/unicode/&lt;version&gt;/</c>. It lives in the tests so that a test can
/// prove the committed table is exactly what the data files say (<see cref="UnicodeDataTests"/>); run the tests
/// with <c>UPDATE_GENERATED=1</c> to rewrite the table after updating the data files.
/// </summary>
/// <remarks>
/// File formats: UAX #44 §4.2 ("File Format Conventions"): <c>code point or range ; value # comment</c>, with
/// <c># @missing: range; value</c> lines that give the value of every code point the file does not list. The
/// @missing lines are applied first, in file order, then the listed entries.
/// </remarks>
internal static class UnicodeDataGenerator
{
    public const string Version = "18.0.0";
    private const int CodePointCount = 0x110000;

    public static string DataFolder([CallerFilePath] string thisFile = "") =>
        Path.GetFullPath(Path.Combine(Path.GetDirectoryName(thisFile)!, "..", "assets", "unicode", Version));

    public static string GeneratedFile([CallerFilePath] string thisFile = "") =>
        Path.GetFullPath(Path.Combine(Path.GetDirectoryName(thisFile)!, "..", "Ave.Extensions.Documents.Typesetting", "Unicode", "UnicodePropertyRanges.g.cs"));

    public static string GeneratedNormalizationFile([CallerFilePath] string thisFile = "") =>
        Path.GetFullPath(Path.Combine(Path.GetDirectoryName(thisFile)!, "..", "Ave.Extensions.Documents.Typesetting", "Unicode", "UnicodeNormalizationData.g.cs"));

    public static string GeneratedRightToLeftFile([CallerFilePath] string thisFile = "") =>
        Path.GetFullPath(Path.Combine(Path.GetDirectoryName(thisFile)!, "..", "Ave.Extensions.Documents.Core", "RightToLeftCharacters.g.cs"));

    /// <summary>
    /// The source text of the table of the characters that ask for right-to-left text: from UnicodeData.txt (UAX #44
    /// §5.7.1, field 4, Bidi_Class) every code point whose class is R, AL, AN, RLE, RLO or RLI, as ranges of consecutive
    /// code points of one class. A pair of <c>&lt;…, First&gt;</c> and <c>&lt;…, Last&gt;</c> lines stands for every code
    /// point between them. A code point the file does not list is in no range.
    /// </summary>
    public static string GenerateRightToLeft()
    {
        var classes = new string?[CodePointCount];
        string? first = null;
        foreach (var line in File.ReadAllLines(Path.Combine(DataFolder(), "UnicodeData.txt")))
        {
            var fields = line.Split(';');
            var value = fields[4] is "R" or "AL" or "AN" or "RLE" or "RLO" or "RLI" ? fields[4] : null;
            if (fields[1].EndsWith(", First>", StringComparison.Ordinal))
            {
                first = fields[0];
                continue;
            }

            if (value is not null)
            {
                Fill(classes, fields[1].EndsWith(", Last>", StringComparison.Ordinal) ? first! : fields[0], fields[0], value);
            }

            first = null;
        }

        var lines = new List<string>();
        for (var codePoint = 0; codePoint < CodePointCount; codePoint++)
        {
            if (classes[codePoint] is not { } value)
            {
                continue;
            }

            var last = codePoint;
            while (last + 1 < CodePointCount && classes[last + 1] == value)
            {
                last++;
            }

            lines.Add($"        new(0x{codePoint.ToString("X4", CultureInfo.InvariantCulture)}, 0x{last.ToString("X4", CultureInfo.InvariantCulture)}, RightToLeftClass.{value}),");
            codePoint = last;
        }

        var source = new StringBuilder();
        source.Append("// <auto-generated>\n");
        source.Append($"// Generated from the Unicode Character Database {Version}: assets/unicode/{Version}/UnicodeData.txt (field 4,\n");
        source.Append("// Bidi_Class), by UnitTests.Extensions.Documents.Typesetting/UnicodeDataGenerator.cs. Do not edit: run the tests\n");
        source.Append("// with UPDATE_GENERATED=1 to regenerate.\n");
        source.Append("// </auto-generated>\n");
        source.Append("namespace Ave.Extensions.Documents.Core;\n\n");
        source.Append("public static partial class RightToLeftCharacters\n{\n");
        source.Append("    /// <summary>The version of the Unicode Character Database the table was generated from.</summary>\n");
        source.Append($"    internal const string UnicodeVersion = \"{Version}\";\n\n");
        source.Append("    /// <summary>Every code point whose Bidi_Class is R, AL, AN, RLE, RLO or RLI, as ranges in code point order.</summary>\n");
        source.Append("    private static readonly Range[] Ranges =\n    [\n");
        foreach (var line in lines)
        {
            source.Append(line).Append('\n');
        }

        source.Append("    ];\n}\n");
        return source.ToString();
    }

    /// <summary>
    /// The source text of the normalization table: from UnicodeData.txt (UAX #44 §5.7.1, fields 3 and 5) every code point
    /// with a non-zero Canonical_Combining_Class, and every canonical decomposition (a mapping without a
    /// <c>&lt;tag&gt;</c>: one or two code points), each marked when DerivedNormalizationProps.txt lists the code point as
    /// Full_Composition_Exclusion, so that canonical composition (UAX #15 §1.3) never makes it. Hangul syllables are
    /// algorithmic (the Unicode Standard §3.12) and not in the table.
    /// </summary>
    public static string GenerateNormalization()
    {
        var excluded = Values("DerivedNormalizationProps.txt", field: 1, onlyValue: "Full_Composition_Exclusion");
        var classes = new List<string>();
        var decompositions = new List<string>();
        foreach (var line in File.ReadAllLines(Path.Combine(DataFolder(), "UnicodeData.txt")))
        {
            var fields = line.Split(';');
            var codePoint = int.Parse(fields[0], NumberStyles.HexNumber, CultureInfo.InvariantCulture);
            if (fields[3] != "0")
            {
                classes.Add($"        new(0x{fields[0]}, {fields[3]}),");
            }

            if (fields[5].Length > 0 && !fields[5].StartsWith('<'))
            {
                var parts = fields[5].Split(' ');
                var second = parts.Length > 1 ? "0x" + parts[1] : "-1";
                var composes = excluded[codePoint] is null ? "true" : "false";
                decompositions.Add($"        new(0x{fields[0]}, 0x{parts[0]}, {second}, {composes}),");
            }
        }

        var source = new StringBuilder();
        source.Append("// <auto-generated>\n");
        source.Append($"// Generated from the Unicode Character Database {Version}: assets/unicode/{Version}/UnicodeData.txt and\n");
        source.Append("// DerivedNormalizationProps.txt, by UnitTests.Extensions.Documents.Typesetting/UnicodeDataGenerator.cs. Do not edit:\n");
        source.Append("// run the tests with UPDATE_GENERATED=1 to regenerate.\n");
        source.Append("// </auto-generated>\n");
        source.Append("namespace Ave.Extensions.Documents.Typesetting.Unicode;\n\n");
        source.Append("internal static partial class Normalization\n{\n");
        source.Append("    /// <summary>Every code point with a non-zero Canonical_Combining_Class, in code point order.</summary>\n");
        source.Append("    private static readonly CombiningClass[] CombiningClasses =\n    [\n");
        foreach (var line in classes)
        {
            source.Append(line).Append('\n');
        }

        source.Append("    ];\n\n");
        source.Append("    /// <summary>Every canonical decomposition, in code point order.</summary>\n");
        source.Append("    private static readonly Decomposition[] Decompositions =\n    [\n");
        foreach (var line in decompositions)
        {
            source.Append(line).Append('\n');
        }

        source.Append("    ];\n}\n");
        return source.ToString();
    }

    /// <summary>The source text of the generated table.</summary>
    public static string Generate()
    {
        var lineBreak = Values("LineBreak.txt", field: 1);
        var eastAsianWidth = Values("EastAsianWidth.txt", field: 1);
        var category = Values("DerivedGeneralCategory.txt", field: 1);
        var pictographic = Values("emoji-data.txt", field: 1, onlyValue: "Extended_Pictographic");
        var script = Values("Scripts.txt", field: 1);
        var ignorable = Values("DerivedCoreProperties.txt", field: 1, onlyValue: "Default_Ignorable_Code_Point");

        var lines = new List<string>();
        string? previous = null;
        for (var codePoint = 0; codePoint < CodePointCount; codePoint++)
        {
            var entry = $"{lineBreak[codePoint]}, {Traits(eastAsianWidth[codePoint], category[codePoint], pictographic[codePoint] is not null, ignorable[codePoint] is not null)}, {Script(script[codePoint])}";
            if (entry != previous)
            {
                lines.Add($"        new(0x{codePoint.ToString("X4", CultureInfo.InvariantCulture)}, {entry}),");
                previous = entry;
            }
        }

        var source = new StringBuilder();
        source.Append("// <auto-generated>\n");
        source.Append($"// Generated from the Unicode Character Database {Version}: assets/unicode/{Version}/LineBreak.txt,\n");
        source.Append("// EastAsianWidth.txt, DerivedGeneralCategory.txt, emoji-data.txt, Scripts.txt and DerivedCoreProperties.txt, by\n");
        source.Append("// UnitTests.Extensions.Documents.Typesetting/UnicodeDataGenerator.cs. Do not edit: run the tests with\n");
        source.Append("// UPDATE_GENERATED=1 to regenerate. Each entry starts a range that ends where the next one starts.\n");
        source.Append("// </auto-generated>\n");
        source.Append("using static Ave.Extensions.Documents.Typesetting.Unicode.CharacterTraits;\n");
        source.Append("using static Ave.Extensions.Documents.Typesetting.Unicode.LineBreakClass;\n\n");
        source.Append("namespace Ave.Extensions.Documents.Typesetting.Unicode;\n\n");
        source.Append("internal static partial class UnicodeProperties\n{\n");
        source.Append("    /// <summary>The version of the Unicode Character Database the table was generated from.</summary>\n");
        source.Append($"    public const string UnicodeVersion = \"{Version}\";\n\n");
        source.Append("    private static readonly Range[] Ranges =\n    [\n");
        foreach (var line in lines)
        {
            source.Append(line).Append('\n');
        }

        source.Append("    ];\n}\n");
        return source.ToString();
    }

    private static string Traits(string? eastAsianWidth, string? category, bool pictographic, bool ignorable)
    {
        var traits = new List<string>();
        if (ignorable)
        {
            traits.Add("DefaultIgnorable");
        }

        if (eastAsianWidth is "F" or "W" or "H")
        {
            traits.Add("EastAsian");
        }

        if (pictographic)
        {
            traits.Add("ExtendedPictographic");
        }

        traits.AddRange(category switch
        {
            "Mn" => ["Mark", "NonspacingMark"],
            "Mc" => ["Mark"],
            "Pi" => ["InitialPunctuation"],
            "Pf" => ["FinalPunctuation"],
            "Cn" => ["Unassigned"],
            _ => Array.Empty<string>(),
        });
        return traits.Count == 0 ? "None" : string.Join(" | ", traits);
    }

    /// <summary>The Script value as <c>TextScript</c> names it; every script but the five named ones is Other.</summary>
    private static string Script(string? value) => value switch
    {
        "Common" or "Inherited" or "Latin" or "Greek" or "Cyrillic" => "TextScript." + value,
        _ => "TextScript.Other",
    };

    private static readonly Regex Missing = new(@"^#\s*@missing:\s*([0-9A-F]+)(?:\.\.([0-9A-F]+))?\s*;\s*([^\s;#]+)", RegexOptions.CultureInvariant);

    /// <summary>The value of one field for every code point (null where the file gives none).</summary>
    public static string?[] Values(string file, int field, string? onlyValue = null)
    {
        var values = new string?[CodePointCount];
        var lines = File.ReadAllLines(Path.Combine(DataFolder(), file));
        // The @missing defaults apply to the property the file is about. A file of several binary properties
        // (DerivedCoreProperties.txt) states defaults for its enumerated ones too ("@missing: 0000..10FFFF; InCB;
        // None"); for one binary property, picked with onlyValue, a code point that is not listed simply lacks it.
        foreach (var match in lines.Select(line => Missing.Match(line)).Where(match => match.Success && onlyValue is null))
        {
            Fill(values, match.Groups[1].Value, match.Groups[2].Success ? match.Groups[2].Value : match.Groups[1].Value, match.Groups[3].Value);
        }

        foreach (var line in lines)
        {
            var data = line.Split('#')[0].Trim();
            if (data.Length == 0)
            {
                continue;
            }

            var fields = data.Split(';').Select(part => part.Trim()).ToArray();
            if (onlyValue is not null && fields[field] != onlyValue)
            {
                continue;
            }

            var range = fields[0].Split("..");
            Fill(values, range[0], range.Length > 1 ? range[1] : range[0], fields[field]);
        }

        return values;
    }

    private static void Fill(string?[] values, string first, string last, string value)
    {
        for (var codePoint = int.Parse(first, NumberStyles.HexNumber, CultureInfo.InvariantCulture);
             codePoint <= int.Parse(last, NumberStyles.HexNumber, CultureInfo.InvariantCulture);
             codePoint++)
        {
            values[codePoint] = value;
        }
    }
}
