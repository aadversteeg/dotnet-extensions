    private static string Chromium([CallerFilePath] string thisFile = "") =>
        Path.GetFullPath(Path.Combine(Path.GetDirectoryName(thisFile)!, "..", "tools", "reference", "chromium"));

    [Fact]
    public void Every_case_has_its_four_measured_files_and_nothing_else_is_measured()
    {
        var cases = Directory.GetFiles(Path.Combine(Chromium(), "cases"), "*.html").Select(Path.GetFileNameWithoutExtension).Order(StringComparer.Ordinal).ToList();
        var measured = Directory.GetFiles(Path.Combine(Chromium(), "measured")).Select(Path.GetFileName).Order(StringComparer.Ordinal).ToList();

        cases.Should().HaveCount(770);
        cases.Should().HaveCount(770);
        cases.Should().HaveCount(770);
        cases.Should().HaveCount(770);
        cases.Should().HaveCount(770);
        cases.Should().HaveCount(770);
        measured.Should().Equal(cases.SelectMany(name => new[] { "boxes", "lines", "print", "words" }.Select(kind => $"{name}.{kind}.txt")).Append("versions.txt")
            .Append("a2-row-end-family.tsv").Concat(InkCases.Select(name => $"{name}.ink.txt")).Concat(LinkCases.Select(name => $"{name}.links.txt")).Order(StringComparer.Ordinal),
            "four files per case, the versions, Chromium's words of the generated a2-row-end family (RowEndTests), the gaps of the cases whose print skips ink, and the link annotations of the cases whose print has any");
        measured.Should().Equal(Lines.Keys.Order(StringComparer.Ordinal), "the pinned list names every measured file");
    }

    [Fact]
    public void Every_measured_file_has_the_lines_it_was_measured_with()
    {
        foreach (var (name, count) in Lines)
        {
            File.ReadAllText(Path.Combine(Chromium(), "measured", name)).Count(character => character == '\n').Should().Be(count, name);
        }
    }
