#!/usr/bin/env python3
"""Writes the encoding label table of the HTML parser from the Encoding Standard's encodings.json.

The Encoding Standard, section 4.2 "Names and labels", publishes the table as JSON at
https://encoding.spec.whatwg.org/encodings.json. Download it, then run:

    python3 -I tools/generate-encoding-labels.py encodings.json \
        Ave.Extensions.Documents.Html.Parsing/Decoding/EncodingLabels.g.cs

The parser needs only to know which encoding a label names, to tell UTF-8 from every other encoding (HTML Standard
section 13.2.3.2, "prescan a byte stream", and 13.2.6.4.4, "in head" for meta); it decodes nothing but UTF-8 and UTF-16.
"""

import hashlib
import json
import sys


def main(source: str, target: str) -> None:
    data = open(source, 'rb').read()
    groups = json.loads(data.decode('utf-8'))
    pairs = sorted(
        ((label, encoding['name']) for group in groups for encoding in group['encodings'] for label in encoding['labels']),
        key=lambda pair: pair[0])
    lines = [
        '// Generated by tools/generate-encoding-labels.py from the Encoding Standard\'s encodings.json',
        f'// (https://encoding.spec.whatwg.org/encodings.json, SHA-256 {hashlib.sha256(data).hexdigest()}).',
        '// Copyright (c) WHATWG (Apple, Google, Mozilla, Microsoft); as a portion incorporated into source code, licensed',
        '// under the BSD 3-Clause License (see libs/documents/NOTICE.md). Do not edit.',
        'using System.Collections.Frozen;',
        'using System.Collections.Generic;',
        '',
        'namespace Ave.Extensions.Documents.Html.Parsing.Decoding;',
        '',
        'internal static partial class EncodingLabels',
        '{',
        f'    /// <summary>Every label of the Encoding Standard ({len(pairs)}), lowercase, to the name of its encoding.</summary>',
        '    private static readonly FrozenDictionary<string, string> Names = new Dictionary<string, string>',
        '    {',
    ]
    lines += [f'        ["{label}"] = "{name}",' for label, name in pairs]
    lines += ['    }.ToFrozenDictionary();', '}', '']
    with open(target, 'w', encoding='utf-8', newline='\n') as output:
        output.write('\n'.join(lines))


if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])
