#!/usr/bin/env python3
"""Writes the named character reference table of the HTML parser from the HTML Standard's entities.json.

The HTML Standard, section 13.5 "Named character references", publishes the table as JSON at
https://html.spec.whatwg.org/entities.json. Download it, then run:

    python3 -I tools/generate-html-entities.py entities.json \
        Ave.Extensions.Documents.Html.Parsing/Tokenizing/named-character-references.txt

One line per name: the name without the leading ampersand (with its semicolon where it has one), a space, and the
code points it stands for in hexadecimal, separated by spaces. Lines are sorted by name (ordinal), so the file is the
same for the same table. The first lines are comments (#) naming the source and its SHA-256.
"""

import hashlib
import json
import sys


def main(source: str, target: str) -> None:
    data = open(source, 'rb').read()
    table = json.loads(data.decode('utf-8'))
    lines = [
        '# Named character references, HTML Standard section 13.5 (https://html.spec.whatwg.org/entities.json)',
        '# Copyright (c) WHATWG (Apple, Google, Mozilla, Microsoft); as a portion incorporated into source code,',
        '# licensed under the BSD 3-Clause License (see libs/documents/NOTICE.md).',
        f'# entities.json SHA-256 {hashlib.sha256(data).hexdigest()}, {len(table)} names.',
        '# Generated by tools/generate-html-entities.py; do not edit.',
    ]
    for name in sorted(table, key=lambda key: key.encode('utf-8')):
        if not name.startswith('&'):
            raise ValueError(f'name without ampersand: {name}')
        codepoints = ' '.join(f'{codepoint:X}' for codepoint in table[name]['codepoints'])
        lines.append(f'{name[1:]} {codepoints}')
    with open(target, 'w', encoding='utf-8', newline='\n') as output:
        output.write('\n'.join(lines) + '\n')


if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])
