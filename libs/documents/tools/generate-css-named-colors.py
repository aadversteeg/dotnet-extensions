#!/usr/bin/env python3
"""Writes the named colour table of the CSS reader from the colour keyword files of css-parsing-tests.

The files are vendored in assets/test-suites/css-parsing-tests (CC0 1.0, public domain): color_keywords_3.json and
color_keywords_4.json pair every named colour of CSS Color 4 with its rgb() value. Run from libs/documents:

    python3 -I tools/generate-css-named-colors.py \
        assets/test-suites/css-parsing-tests Ave.Extensions.Documents.Css/Values/NamedColors.g.cs

Each name of the table is also checked against the colour Chromium 159 computes for it
(tools/reference/chromium/computed-style/measured/named-colors.txt, UnitTests.Extensions.Documents.Css/
NamedColorTests.cs).
"""

import hashlib
import json
import os
import re
import sys


def main(folder: str, target: str) -> None:
    colors = {}
    digests = []
    for name in ('color_keywords_3.json', 'color_keywords_4.json'):
        data = open(os.path.join(folder, name), 'rb').read()
        digests.append(f'{name} {hashlib.sha256(data).hexdigest()}')
        items = json.loads(data.decode('utf-8'))
        for keyword, expected in zip(items[0::2], items[1::2]):
            # A named colour is a lowercase keyword with an rgb() value; the files also test case, white space,
            # comments, transparent and invalid names, which are not table entries.
            match = re.fullmatch(r'rgb\((\d+), (\d+), (\d+)\)', expected or '')
            if re.fullmatch(r'[a-z]+', keyword) and match:
                colors[keyword] = tuple(int(part) for part in match.groups())
    if len(colors) != 148:
        raise ValueError(f'expected 148 named colours, found {len(colors)}')
    lines = [
        '// Generated by tools/generate-css-named-colors.py from the colour keyword files of css-parsing-tests (CC0 1.0,',
        '// assets/test-suites/css-parsing-tests at 203ce36), checked against Chromium 159 by NamedColorTests. SHA-256:',
        *[f'// {digest}' for digest in digests],
        '// Do not edit.',
        'using System.Collections.Frozen;',
        'using System.Collections.Generic;',
        '',
        'namespace Ave.Extensions.Documents.Css.Values;',
        '',
        'internal static partial class Colors',
        '{',
        f'    /// <summary>The {len(colors)} named colours of CSS Color 4, lowercase, to their sRGB value.</summary>',
        '    private static readonly FrozenDictionary<string, (byte Red, byte Green, byte Blue)> Named = new Dictionary<string, (byte, byte, byte)>',
        '    {',
    ]
    for name in sorted(colors):
        red, green, blue = colors[name]
        lines.append(f'        ["{name}"] = (0x{red:02x}, 0x{green:02x}, 0x{blue:02x}),')
    lines += ['    }.ToFrozenDictionary();', '}', '']
    with open(target, 'w', encoding='utf-8', newline='\n') as output:
        output.write('\n'.join(lines))


if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])
