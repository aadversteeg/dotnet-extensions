#!/usr/bin/env python3
"""Writes the named colour table of the CSS reader from CSS Color 4 section 6.1, "Named Colors".

Download the editor's draft (https://drafts.csswg.org/css-color-4/) as HTML, then run:

    python3 -I tools/generate-css-named-colors.py css-color-4.html \
        Ave.Extensions.Documents.Css/Values/NamedColors.g.cs

The table in the specification (class "named-color-table") lists each keyword with its hex value; this script reads
its rows and writes them sorted by name.
"""

import hashlib
import html
import re
import sys


def main(source: str, target: str) -> None:
    data = open(source, 'rb').read()
    text = data.decode('utf-8')
    # The rows omit their end tags: each has a <dfn id="valdef-color-NAME"> and a cell "<td>#rrggbb".
    start = text.index('class="named-color-table"')
    end = text.index('</table>', start)
    colors = {}
    for row in text[start:end].split('<tr>')[1:]:
        name = re.search(r'<dfn [^\n]*?id="valdef-color-([a-z]+)"', row)
        value = re.search(r'<td>(#[0-9a-f]{6})', row)
        if name and value:
            colors[name.group(1)] = value.group(1)
    if len(colors) != 148:
        raise ValueError(f'expected 148 named colours, found {len(colors)}')
    lines = [
        '// Generated by tools/generate-css-named-colors.py from CSS Color 4 §6.1 (https://drafts.csswg.org/css-color-4/,',
        f'// SHA-256 {hashlib.sha256(data).hexdigest()}). Do not edit.',
        'using System.Collections.Frozen;',
        'using System.Collections.Generic;',
        '',
        'namespace Ave.Extensions.Documents.Css.Values;',
        '',
        'internal static partial class Colors',
        '{',
        f'    /// <summary>The {len(colors)} named colours of CSS Color 4 §6.1, lowercase, to their sRGB value.</summary>',
        '    private static readonly FrozenDictionary<string, (byte Red, byte Green, byte Blue)> Named = new Dictionary<string, (byte, byte, byte)>',
        '    {',
    ]
    for name in sorted(colors):
        value = colors[name]
        lines.append(f'        ["{name}"] = (0x{value[1:3]}, 0x{value[3:5]}, 0x{value[5:7]}),')
    lines += ['    }.ToFrozenDictionary();', '}', '']
    with open(target, 'w', encoding='utf-8', newline='\n') as output:
        output.write('\n'.join(lines))


if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])
